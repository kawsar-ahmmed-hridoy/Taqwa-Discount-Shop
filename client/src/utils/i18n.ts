const interpolate = (value: string, params?: Record<string, string | number>) => {
  if (!params) return value;
  return value.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? `{${key}}`));
};

export const translateText = (language: Language, key: string, params?: Record<string, string | number>) => {
  const resolved = language === 'bn' ? TRANSLATIONS[key] ?? key : key;
  return interpolate(resolved, params);
};

const ENGLISH_ENTRIES = Object.entries(TRANSLATIONS).sort((a, b) => b[0].length - a[0].length);
const BENGALI_ENTRIES = Object.entries(TRANSLATIONS)
  .map(([english, bangla]) => [bangla, english] as const)
  .sort((a, b) => b[0].length - a[0].length);

const escapeRegExp = (value: string) => value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export const translatePhrase = (language: Language, value: string) => {
  if (!value) return value;

  const entries = language === 'bn' ? ENGLISH_ENTRIES : BENGALI_ENTRIES;
  return entries.reduce(
    (current, [from, to]) => current.replace(new RegExp(escapeRegExp(from), 'g'), to),
    value
  );
};

